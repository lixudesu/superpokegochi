import { access, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptsDir = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(scriptsDir, '..');
const assetsDir = join(rootDir, 'assets', 'pokemons');
const normalDir = join(assetsDir, 'Front');
const shinyDir = join(assetsDir, 'Front shiny');
const outputPath = join(rootDir, 'pokemon-catalog.js');
const speciesUrl = 'https://pokeapi.co/api/v2/pokemon-species?limit=2000';

const normalize = value => value.toLowerCase().replace(/[^a-z0-9]/g, '');

const displayName = slug => {
  const special = {
    'nidoran-f': 'Nidoran F',
    'nidoran-m': 'Nidoran M',
    'mr-mime': 'Mr. Mime',
    'mime-jr': 'Mime Jr.',
    'porygon-z': 'Porygon-Z',
    'type-null': 'Type: Null',
    'mr-rime': 'Mr. Rime',
  };
  if (special[slug]) return special[slug];
  if (['ho-oh', 'jangmo-o', 'hakamo-o', 'kommo-o'].includes(slug)) {
    return slug.split('-').map(part => part.charAt(0).toUpperCase() + part.slice(1)).join('-');
  }
  return slug
    .split('-')
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
};

const response = await fetch(speciesUrl);
if (!response.ok) throw new Error(`PokeAPI respondeu com ${response.status}.`);
const speciesPayload = await response.json();
const species = speciesPayload.results;

const spriteIndex = JSON.parse(await readFile(join(assetsDir, 'front-index.json'), 'utf8'));
const baseAssets = spriteIndex.assets.filter(asset => (
  !/_\d+\.webp$/i.test(asset.file) && !/_female\.webp$/i.test(asset.file)
));
const shinyFiles = new Set((await readdir(shinyDir)).map(file => file.toLowerCase()));
const assetByKey = new Map(baseAssets.map(asset => [normalize(asset.file.replace(/\.webp$/i, '')), asset]));

const assetAliases = new Map([
  ['nidoranf', 'nidoranfe'],
  ['nidoranm', 'nidoranma'],
]);

const rows = species.map(item => {
  const speciesKey = normalize(item.name);
  const assetKey = assetAliases.get(speciesKey) || speciesKey;
  const asset = assetByKey.get(assetKey);
  if (!asset) throw new Error(`Sprite principal nao encontrado para ${item.name}.`);
  if (!shinyFiles.has(asset.file.toLowerCase())) {
    throw new Error(`Sprite Shiny nao encontrado para ${asset.file}.`);
  }

  const dexNumber = Number(item.url.match(/\/(\d+)\/$/)?.[1]);
  const frameWidth = asset.width / asset.frames;
  if (!Number.isInteger(frameWidth)) {
    throw new Error(`Largura de frame invalida para ${asset.file}.`);
  }

  return [
    dexNumber,
    item.name,
    displayName(item.name),
    asset.file,
    asset.frames,
    frameWidth,
    asset.height,
    asset.width,
  ];
});

if (rows.length !== baseAssets.length) {
  throw new Error(`Catalogo tem ${rows.length} especies, mas os assets possuem ${baseAssets.length}.`);
}

const generated = `// Generated by scripts/generate-pokemon-catalog.mjs. Do not edit manually.
const POKEMON_CATALOG_DATA = ${JSON.stringify(rows, null, 2)};
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated, 'utf8');
await access(outputPath);
console.log(`Catalogo gerado com ${rows.length} especies em ${outputPath}.`);
